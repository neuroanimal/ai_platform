"""LlamaIndex RAG adapter (``llama-index-core``).

Retrieval runs on a LlamaIndex ``VectorStoreIndex`` built from
``TextNode``s; the embedding model is the platform ``embedder``
(HashingEmbedder by default) wrapped as a LlamaIndex ``BaseEmbedding``, so
nothing calls a hosted embedding service unless you pass ``embed_model``.
Answers are generated by a platform LLM adapter (``llm``).

Configuration (on top of NativeRAGAdapter's shared keys):

    embed_model   a LlamaIndex embedding model (overrides ``embedder``)
    embedder      platform Embedder (default HashingEmbedder)

Not verified against an installed LlamaIndex here (the package was not
installed when this was written); unit tests cover the calls through a fake
module. Previously a stub returning a fabricated answer; the class name and
the RAGAdapter methods are unchanged.
"""

from typing import Any, Dict, List

from ai_platform.common.rag.embedder import HashingEmbedder
from ai_platform.common.rag.native_rag_adapter import NativeRAGAdapter, RAGError


def wrap_embedder(embedder, base_cls):
    """Expose a platform Embedder as a LlamaIndex BaseEmbedding."""

    class PlatformEmbedding(base_cls):  # pylint: disable=too-few-public-methods
        """LlamaIndex view of a platform embedder."""

        def _get_query_embedding(self, query: str) -> List[float]:
            return embedder.embed_one(query)

        def _get_text_embedding(self, text: str) -> List[float]:
            return embedder.embed_one(text)

        def _get_text_embeddings(self, texts: List[str]) -> List[List[float]]:
            return embedder.embed(texts)

        async def _aget_query_embedding(self, query: str) -> List[float]:
            return embedder.embed_one(query)

    return PlatformEmbedding(model_name="ai_platform")


class LlamaIndexAdapter(NativeRAGAdapter):
    """RAG on a LlamaIndex VectorStoreIndex."""

    STACK = "llamaindex"

    def __init__(self):
        super().__init__()
        self._index = None
        self._node_cls = None

    def _setup(self, config: Dict[str, Any]) -> None:
        try:
            from llama_index.core import VectorStoreIndex  # pylint: disable=import-outside-toplevel
            from llama_index.core.embeddings import BaseEmbedding  # pylint: disable=import-outside-toplevel
            from llama_index.core.schema import TextNode  # pylint: disable=import-outside-toplevel
        except ImportError as exc:
            raise RAGError("LlamaIndexAdapter requires: pip install llama-index-core") from exc
        self._node_cls = TextNode
        embed_model = config.get("embed_model") or wrap_embedder(
            config.get("embedder") or HashingEmbedder(), BaseEmbedding)
        self._index = VectorStoreIndex(nodes=[], embed_model=embed_model)

    def ingest(self, documents: List[Dict[str, Any]]) -> None:
        """Chunk documents and insert them as nodes."""
        self._require()
        texts, metadata = self.chunk_documents(documents)
        if texts:
            self._index.insert_nodes([self._node_cls(id_=m["id"], text=t, metadata=m)
                                      for t, m in zip(texts, metadata)])

    def _retrieve(self, question: str, top_k: int) -> List[Dict[str, Any]]:
        found = self._index.as_retriever(similarity_top_k=top_k).retrieve(question)
        return [self.make_source(item.node.node_id, item.score,
                                 {**item.node.metadata, "text": item.node.get_content()})
                for item in found]

    def _teardown(self) -> None:
        self._index = None
