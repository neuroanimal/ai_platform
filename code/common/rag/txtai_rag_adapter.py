"""txtai RAG adapter (https://neuml.github.io/txtai/).

Retrieval uses a txtai ``Embeddings`` index with ``content=True`` (txtai
stores the text and metadata itself and embeds it with its own model,
``path``); answers are generated by a platform LLM adapter (``llm``).

Configuration (on top of NativeRAGAdapter's shared keys):

    path      txtai embedding model, default
              "sentence-transformers/all-MiniLM-L6-v2" (downloaded on first use)
    txtai     extra txtai Embeddings configuration (dict)

Not verified against an installed txtai here (the package was not installed
when this was written); unit tests cover the calls through a fake module.
Previously a stub returning a fabricated answer; the class name and the
RAGAdapter methods are unchanged.
"""

import json
from typing import Any, Dict, List

from ai_platform.common.rag.native_rag_adapter import NativeRAGAdapter, RAGError


class TxtaiRAGAdapter(NativeRAGAdapter):
    """RAG on a txtai content index."""

    STACK = "txtai"

    def __init__(self):
        super().__init__()
        self._embeddings = None

    def _setup(self, config: Dict[str, Any]) -> None:
        try:
            from txtai import Embeddings  # pylint: disable=import-outside-toplevel
        except ImportError as exc:
            raise RAGError("TxtaiRAGAdapter requires: pip install txtai") from exc
        self._embeddings = Embeddings({
            "path": config.get("path", "sentence-transformers/all-MiniLM-L6-v2"),
            "content": True, **config.get("txtai", {})})

    def ingest(self, documents: List[Dict[str, Any]]) -> None:
        """Chunk documents and upsert them (text + metadata) into txtai."""
        self._require()
        texts, metadata = self.chunk_documents(documents)
        if texts:
            # txtai content rows: (id, {"text": ..., other fields...}, tags)
            self._embeddings.upsert([
                (m["id"], {"text": t, "meta_json": json.dumps(m)}, None)
                for t, m in zip(texts, metadata)])

    def _retrieve(self, question: str, top_k: int) -> List[Dict[str, Any]]:
        rows = self._embeddings.search(
            "select id, text, meta_json, score from txtai where similar(:q)",
            limit=top_k, parameters={"q": question})
        return [self.make_source(r["id"], r["score"],
                                 {**json.loads(r.get("meta_json") or "{}"), "text": r["text"]})
                for r in rows]

    def _teardown(self) -> None:
        if self._embeddings is not None and hasattr(self._embeddings, "close"):
            self._embeddings.close()
        self._embeddings = None
